CREATE TABLE IF NOT EXISTS `zhiye_print_draft` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `user_id` INT NOT NULL,
  `title` VARCHAR(120) NOT NULL,
  `file_name` VARCHAR(255) NOT NULL,
  `file_url` VARCHAR(500) NOT NULL,
  `file_size` BIGINT NOT NULL,
  `sha256` CHAR(64) NOT NULL,
  `page_count` INT NOT NULL,
  `copies` INT NOT NULL DEFAULT 1,
  `shipping_address` JSON NULL,
  `status` VARCHAR(30) NOT NULL DEFAULT 'draft' COMMENT 'uploading/upload_failed/draft/waiting_files/quoted/quote_failed/ordered',
  `external_package_id` VARCHAR(80) NULL,
  `package_create_count` INT NOT NULL DEFAULT 0,
  `package_poll_count` INT NOT NULL DEFAULT 0,
  `quote_attempt_count` INT NOT NULL DEFAULT 0,
  `next_quote_at` DATETIME NULL,
  `quote_operation_id` VARCHAR(36) NULL,
  `cost_print_amount_cents` INT NULL,
  `cost_shipping_amount_cents` INT NULL,
  `cost_total_amount_cents` INT NULL,
  `retail_multiplier` DECIMAL(6,4) NULL,
  `retail_amount_cents` INT NULL,
  `print_config_snapshot` JSON NULL,
  `quote_version` VARCHAR(64) NULL,
  `quote_expires_at` DATETIME NULL,
  `order_id` INT NULL,
  `last_error` TEXT NULL,
  `create_time` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  `update_time` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_zhiye_print_draft_order` (`order_id`),
  KEY `idx_zhiye_print_draft_owner_created` (`user_id`, `create_time`),
  KEY `idx_zhiye_print_draft_owner_hash` (`user_id`, `sha256`),
  KEY `idx_zhiye_print_draft_quote_cooldown` (`status`, `next_quote_at`),
  CONSTRAINT `fk_zhiye_print_draft_user` FOREIGN KEY (`user_id`) REFERENCES `app_user` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_zhiye_print_draft_order` FOREIGN KEY (`order_id`) REFERENCES `order` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `chk_zhiye_print_draft_pages` CHECK (`page_count` BETWEEN 1 AND 2000),
  CONSTRAINT `chk_zhiye_print_draft_copies` CHECK (`copies` BETWEEN 1 AND 99)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='知页用户打印草稿与报价快照';
